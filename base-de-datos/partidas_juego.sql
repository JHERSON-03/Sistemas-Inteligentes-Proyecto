-- Tabla de partidas de los minijuegos (ej. "Atrapa la respuesta").
-- Sigue el patrón <entidad>_<campo> del resto del esquema (ver backend/migraciones/001_renombrar_columnas.sql).
-- Ejecutar una sola vez en el SQL Editor de Supabase.
BEGIN;

CREATE TABLE IF NOT EXISTS public.partidas_juego (
    partida_id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partida_usuario_id  integer      NOT NULL REFERENCES public.usuarios (usuario_id) ON DELETE CASCADE,
    partida_juego       varchar(30)  NOT NULL,
    partida_consigna    varchar(120) NOT NULL,
    partida_puntaje     integer      NOT NULL,
    partida_aciertos    integer      NOT NULL DEFAULT 0 CHECK (partida_aciertos >= 0),
    partida_errores     integer      NOT NULL DEFAULT 0 CHECK (partida_errores >= 0),
    partida_fecha       timestamp    NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

-- Partidas de un alumno (control de reenvíos) y ranking por juego
CREATE INDEX IF NOT EXISTS ix_partidas_juego_partida_usuario_id
    ON public.partidas_juego (partida_usuario_id, partida_juego, partida_fecha);
CREATE INDEX IF NOT EXISTS ix_partidas_juego_ranking
    ON public.partidas_juego (partida_juego, partida_puntaje DESC);

-- Solo el backend (que se conecta como dueño de la tabla) lee y escribe; la API pública de Supabase queda bloqueada.
ALTER TABLE public.partidas_juego ENABLE ROW LEVEL SECURITY;

COMMIT;
